"""Fix round 3, B6: each monthly mountain art's own apex (SPEC V06).

The summit flag used to stand on the trail's last point, which is under the
peak, not on it. This measures the highest point of each background image
(light and dark) and writes `lib/widgets/monthly_climb/climb_summit_table.dart`,
next to the trail table, for `MountainScene` to stand the pole's foot on.

How: a window around the peak is read with ImageMagick (`magick`, already
used by the capture tools; no Python packages needed). The sky colour of
each row is the mean of the window's outer columns; a pixel is mountain when
it is further than a threshold from its row's sky. The mountain is the
masked region connected to a seed just under the peak (so clouds and the
distant ranges do not count). Its highest row gives the apex: the middle of
the columns within 3 px of that row, at the first mountain pixel of that
column. The highest threshold that keeps the seed on the mountain and gives
a narrow cap (no leak into the sky) wins.

Run from the repository root:

    python3 tool/scene_art/summit_apex.py

It prints each measurement and rewrites the Dart table (deterministic: the
same images give the same file). Check the result by eye on a V06 capture
(`FIX3_CAPTURE=1 flutter test test/fix3_summit_apex_test.dart`).
"""

import os
import subprocess
from collections import deque

ROOT = 'assets/climb'
OUT = 'lib/widgets/monthly_climb/climb_summit_table.dart'

# The window around the peaks and the seed, in a 1536 × 2048 image's pixels
# (scaled for another size). Every theme keeps its mountain at the same
# place (scene art S4).
WINDOW = (580, 150, 400, 260)  # x, y, width, height
SEED = (785, 262)
THRESHOLDS = (45, 40, 35, 30, 25, 20)
MAX_CAP = 60  # px: a wider "cap" is a leak into the sky


def size_of(path):
    out = subprocess.check_output(
        ['magick', 'identify', '-format', '%w %h', path], text=True)
    w, h = out.split()
    return int(w), int(h)


def read_window(path, x0, y0, w, h):
    return subprocess.check_output([
        'magick', path, '-crop', f'{w}x{h}+{x0}+{y0}', '+repage',
        '-depth', '8', 'rgb:-'])


def measure(path):
    iw, ih = size_of(path)
    k = iw / 1536
    x0, y0, w, h = (round(v * k) for v in WINDOW)
    sx, sy = round(SEED[0] * k) - x0, round(SEED[1] * k) - y0
    data = read_window(path, x0, y0, w, h)

    def px(x, y):
        i = (y * w + x) * 3
        return data[i], data[i + 1], data[i + 2]

    side = list(range(3, 18)) + list(range(w - 18, w - 3))
    sky = []
    for y in range(h):
        s = [px(x, y) for x in side]
        sky.append(tuple(sum(c[i] for c in s) / len(s) for i in range(3)))
    dist = [[sum((a - b) ** 2 for a, b in zip(px(x, y), sky[y])) ** .5
             for x in range(w)] for y in range(h)]

    for th in THRESHOLDS:
        if dist[sy][sx] <= th:
            continue
        seen = [[False] * w for _ in range(h)]
        seen[sy][sx] = True
        queue = deque([(sx, sy)])
        while queue:
            x, y = queue.popleft()
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                u, v = x + dx, y + dy
                if 0 <= u < w and 0 <= v < h and not seen[v][u] \
                        and dist[v][u] > th:
                    seen[v][u] = True
                    queue.append((u, v))
        top = {}
        for x in range(w):
            for y in range(h):
                if seen[y][x]:
                    top[x] = y
                    break
        if not top:
            continue
        ymin = min(top.values())
        near = [x for x, y in top.items() if y <= ymin + 3]
        if ymin <= 5 or max(near) - min(near) > MAX_CAP:
            continue
        xm = (min(near) + max(near)) // 2
        ax, ay = xm + x0, top[xm] + y0
        return (ax / iw, ay / ih, ax, ay, th, iw, ih)
    raise SystemExit(f'{path}: no apex found')


def main():
    rows = []
    for theme in sorted(os.listdir(ROOT)):
        for mode in ('light', 'dark'):
            path = f'{ROOT}/{theme}/background_{mode}.webp'
            if not os.path.exists(path):
                continue
            nx, ny, ax, ay, th, iw, ih = measure(path)
            print(f'{path}: apex ({ax}, {ay}) of {iw} x {ih} '
                  f'= ({nx:.5f}, {ny:.5f}), threshold {th}')
            rows.append((path, nx, ny, ax, ay))
    lines = [
        '// GENERATED by tool/scene_art/summit_apex.py from the monthly',
        '// mountain art (assets/climb/<theme>/background_<mode>.webp); do not',
        '// edit. Fix round 3, B6.',
        '',
        '/// Each mountain image\'s apex, the highest point of its summit, where',
        '/// the summit flag\'s pole stands (SPEC V06): x ÷ the image width,',
        '/// y ÷ its height, like `climbTrail`. Keyed by the asset.',
        'const climbSummitApex = <String, (double, double)>{',
    ]
    for path, nx, ny, ax, ay in rows:
        lines.append(f"  '{path}': ({nx:.5f}, {ny:.5f}), // px ({ax}, {ay})")
    lines.append('};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
